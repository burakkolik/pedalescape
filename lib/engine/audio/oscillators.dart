/// Phase-accurate oscillators: sine, square, saw, triangle and noise.
///
/// Oscillators keep a running phase accumulator so the frequency can change
/// every sample (sweeps, vibrato, FM) without discontinuities. Square and saw
/// use PolyBLEP correction to tame aliasing at low sample rates.
library;

import 'dart:math' as math;

/// Basic oscillator waveforms.
enum Waveform { sine, square, saw, triangle, noise }

/// Full turn in radians.
const double twoPi = math.pi * 2;

/// A stateful, phase-continuous oscillator.
///
/// Call [next] once per sample with the instantaneous frequency in Hz.
class Oscillator {
  /// Creates an oscillator for [waveform] at [sampleRate] Hz.
  ///
  /// [phase] is the initial phase in cycles (0..1). [pulseWidth] only
  /// affects [Waveform.square]. [seed] drives the noise generator so renders
  /// are deterministic.
  Oscillator(
    this.waveform, {
    required this.sampleRate,
    double phase = 0,
    this.pulseWidth = 0.5,
    int seed = 1,
  }) : _phase = phase - phase.floorToDouble(),
       _noise = NoiseSource(seed: seed);

  /// Waveform generated by this oscillator.
  final Waveform waveform;

  /// Sample rate in Hz.
  final int sampleRate;

  /// Duty cycle for square waves (0..1).
  double pulseWidth;

  double _phase;
  final NoiseSource _noise;

  /// Current phase in cycles (0..1).
  double get phase => _phase;

  /// Resets the phase to [value] cycles.
  void reset([double value = 0]) => _phase = value - value.floorToDouble();

  /// Produces the next sample at [frequency] Hz and advances the phase.
  double next(double frequency) {
    final dt = (frequency / sampleRate).abs().clamp(0.0, 0.5);
    final p = _phase;
    double out;
    switch (waveform) {
      case Waveform.sine:
        out = math.sin(p * twoPi);
      case Waveform.triangle:
        out = 1 - 4 * (p - 0.5).abs();
      case Waveform.saw:
        out = 2 * p - 1 - polyBlep(p, dt);
      case Waveform.square:
        final pw = pulseWidth.clamp(0.05, 0.95);
        out = p < pw ? 1.0 : -1.0;
        out += polyBlep(p, dt);
        var q = p - pw;
        if (q < 0) q += 1;
        out -= polyBlep(q, dt);
      case Waveform.noise:
        out = _noise.next();
    }
    _phase += dt;
    if (_phase >= 1) _phase -= _phase.floorToDouble();
    return out;
  }
}

/// Naive (non band-limited) waveform value at [phase] cycles.
///
/// Useful for LFOs and other control signals where aliasing is irrelevant.
double waveAt(Waveform waveform, double phase, {double pulseWidth = 0.5}) {
  final p = phase - phase.floorToDouble();
  return switch (waveform) {
    Waveform.sine => math.sin(p * twoPi),
    Waveform.square => p < pulseWidth ? 1.0 : -1.0,
    Waveform.saw => 2 * p - 1,
    Waveform.triangle => 1 - 4 * (p - 0.5).abs(),
    Waveform.noise => 0.0,
  };
}

/// PolyBLEP residual used to band-limit discontinuities.
///
/// [t] is the phase (0..1) relative to the discontinuity and [dt] the phase
/// increment per sample.
double polyBlep(double t, double dt) {
  if (dt <= 0) return 0;
  if (t < dt) {
    final x = t / dt;
    return x + x - x * x - 1;
  }
  if (t > 1 - dt) {
    final x = (t - 1) / dt;
    return x * x + x + x + 1;
  }
  return 0;
}

/// Fast deterministic white noise in [-1, 1] (xorshift32).
class NoiseSource {
  /// Creates a noise source; equal seeds produce identical sequences.
  NoiseSource({int seed = 1})
    : _state = (seed == 0 ? 0x9E3779B9 : seed) & _mask;

  static const int _mask = 0xFFFFFFFF;
  int _state;

  /// Next white noise sample in [-1, 1].
  double next() {
    var x = _state;
    x ^= (x << 13) & _mask;
    x ^= x >> 17;
    x ^= (x << 5) & _mask;
    _state = x & _mask;
    return _state / 2147483647.5 - 1.0;
  }
}

/// Converts a MIDI note number (69 = A4) to a frequency in Hz.
double midiToHz(num midi) => 440.0 * math.pow(2, (midi - 69) / 12).toDouble();

/// Ratio for transposing a frequency by [semitones].
double semitoneRatio(num semitones) => math.pow(2, semitones / 12).toDouble();
